import { createAppJwt } from "./github-app";
import { neutralizeMentions } from "./neutralize-mentions";
import { PublishRejected, type PublishInput } from "./run-machine";

const API = "https://api.github.com";

export type PublishRequest = PublishInput;

export interface PublisherConfig {
  appId: string;
  privateKeyPem: string;
  fetch?: typeof fetch;
  nowSeconds?: () => number;
}

export class GitHubError extends Error {
  constructor(
    readonly method: string,
    readonly route: string,
    readonly status: number,
  ) {
    // Only the method, the route and the status: never headers, bodies or tokens.
    super(`GitHub ${method} ${route} failed with ${status}`);
    this.name = "GitHubError";
  }
}

export { neutralizeMentions };

export const branchName = (issueNumber: number, runId: string) =>
  `factory/issue-${issueNumber}-${runId}`;

function prBody(input: PublishInput): string {
  return [
    `Closes #${input.issueNumber}`,
    "",
    `This pull request was generated by an AI agent (Claude Code, model \`${input.model}\`) in an isolated sandbox for run \`${input.runId}\`. The content is agent-generated: a second AI engine reviews it, and a person decides when the risk policy of the repository requires it.`,
    "",
    "The factory merges this pull request only after an approving review at the final commit, all required checks and, for risky changes, an approval from an operator.",
  ].join("\n");
}

export interface Json {
  [key: string]: unknown;
}

export interface GitHubResponse {
  status: number;
  data: unknown;
  text: string;
  headers: Headers;
}

/**
 * One GitHub REST call. Statuses in `accept` are returned instead of thrown. The error
 * carries only the method, the route without its query and the status.
 */
export async function githubRequest(
  doFetch: typeof fetch,
  auth: string,
  method: string,
  route: string,
  options: { body?: unknown; accept?: number[]; mediaType?: string } = {},
): Promise<GitHubResponse> {
  const {
    body,
    accept = [],
    mediaType = "application/vnd.github+json",
  } = options;
  const response = await doFetch(`${API}${route}`, {
    method,
    headers: {
      authorization: `Bearer ${auth}`,
      accept: mediaType,
      "x-github-api-version": "2022-11-28",
      "user-agent": "software-factory-control",
      ...(body === undefined ? {} : { "content-type": "application/json" }),
    },
    ...(body === undefined ? {} : { body: JSON.stringify(body) }),
  });
  const text = await response.text();
  if (!response.ok && !accept.includes(response.status)) {
    throw new GitHubError(
      method,
      route.split("?")[0] ?? route,
      response.status,
    );
  }
  let data: unknown = undefined;
  try {
    data = text === "" ? undefined : JSON.parse(text);
  } catch {
    data = undefined;
  }
  return { status: response.status, data, text, headers: response.headers };
}

export const field = (data: unknown, ...path: string[]): unknown => {
  let current: unknown = data;
  for (const key of path) {
    if (typeof current !== "object" || current === null) return undefined;
    current = (current as Json)[key];
  }
  return current;
};
export const str = (data: unknown, ...path: string[]): string => {
  const v = field(data, ...path);
  if (typeof v !== "string" || v === "")
    throw new Error("unexpected GitHub response");
  return v;
};

/** Looks up the App's installation for a repository and creates a token limited to that repository. */
export async function createInstallationToken(
  config: PublisherConfig,
  repo: string,
  permissions: Record<string, string>,
  accept: number[] = [],
): Promise<{ status: number; token?: string; expiresAt?: number }> {
  const doFetch = config.fetch ?? fetch;
  const nowSeconds = config.nowSeconds ?? (() => Math.floor(Date.now() / 1000));
  const jwt = await createAppJwt({
    appId: config.appId,
    privateKeyPem: config.privateKeyPem,
    nowSeconds: nowSeconds(),
  });
  const [, name] = repo.split("/") as [string, string];
  const found = await githubRequest(
    doFetch,
    jwt,
    "GET",
    `/repos/${repo}/installation`,
  );
  const id = field(found.data, "id");
  if (typeof id !== "number") throw new Error("unexpected GitHub response");
  const created = await githubRequest(
    doFetch,
    jwt,
    "POST",
    `/app/installations/${id}/access_tokens`,
    { body: { repositories: [name], permissions }, accept },
  );
  if (created.status >= 300) return { status: created.status };
  const expires = Date.parse(
    typeof field(created.data, "expires_at") === "string"
      ? (field(created.data, "expires_at") as string)
      : "",
  );
  return {
    status: created.status,
    token: str(created.data, "token"),
    ...(Number.isFinite(expires) ? { expiresAt: expires } : {}),
  };
}

export function createPublisher(config: PublisherConfig) {
  const doFetch = config.fetch ?? fetch;

  async function api(
    auth: string,
    method: string,
    route: string,
    body?: unknown,
    accept: number[] = [],
  ): Promise<{ status: number; data: unknown }> {
    const r = await githubRequest(doFetch, auth, method, route, {
      ...(body === undefined ? {} : { body }),
      accept,
    });
    return { status: r.status, data: r.data };
  }

  async function installationToken(repo: string): Promise<string> {
    const r = await createInstallationToken(config, repo, {
      contents: "write",
      pull_requests: "write",
      issues: "write",
    });
    if (r.token === undefined) throw new Error("unexpected GitHub response");
    return r.token;
  }

  /** Modes in the base tree. Used instead of any mode the container reports. */
  async function baseModes(token: string, repoRoute: string, treeSha: string) {
    const tree = await api(
      token,
      "GET",
      `${repoRoute}/git/trees/${treeSha}?recursive=1`,
    );
    if (field(tree.data, "truncated") === true) {
      throw new Error("base tree is too large to inspect");
    }
    const entries = field(tree.data, "tree");
    const modes = new Map<string, string>();
    if (Array.isArray(entries)) {
      for (const entry of entries) {
        const path = field(entry, "path");
        const mode = field(entry, "mode");
        if (typeof path === "string" && typeof mode === "string") {
          modes.set(path, mode);
        }
      }
    }
    return modes;
  }

  async function publish(input: PublishInput) {
    const token = await installationToken(input.repo);
    const owner = input.repo.split("/")[0] as string;
    const repoRoute = `/repos/${input.repo}`;
    const branch = branchName(input.issueNumber, input.runId);

    const repoInfo = await api(token, "GET", repoRoute);
    const defaultBranch = str(repoInfo.data, "default_branch");
    const baseCommit = await api(
      token,
      "GET",
      `${repoRoute}/git/commits/${input.baseSha}`,
    );
    const baseTree = str(baseCommit.data, "tree", "sha");

    const modes = await baseModes(token, repoRoute, baseTree);
    const modeFor = (path: string): "100644" | "100755" => {
      const segments = path.split("/");
      // A symlink or submodule anywhere on the path would redirect where the file lands.
      for (let i = 1; i <= segments.length; i++) {
        const base = modes.get(segments.slice(0, i).join("/"));
        if (base === "120000") throw new PublishRejected("symlink");
        if (base === "160000") throw new PublishRejected("submodule");
      }
      return modes.get(path) === "100755" ? "100755" : "100644";
    };
    for (const change of input.changes) {
      if (change.status !== "deleted") modeFor(change.path);
    }

    // The commit the pull request must point at: the factory's own, pinned for review and merge.
    let headSha: string;
    // Skip the commit work when an earlier attempt already created the branch.
    const existingRef = await api(
      token,
      "GET",
      `${repoRoute}/git/ref/heads/${branch}`,
      undefined,
      [404],
    );
    if (existingRef.status !== 404) {
      headSha = str(existingRef.data, "object", "sha");
    } else {
      const tree: Json[] = [];
      for (const change of input.changes) {
        if (change.status === "deleted") {
          tree.push({
            path: change.path,
            mode: "100644",
            type: "blob",
            sha: null,
          });
          continue;
        }
        const blob = await api(token, "POST", `${repoRoute}/git/blobs`, {
          content: change.contentBase64 ?? "",
          encoding: "base64",
        });
        tree.push({
          path: change.path,
          mode: modeFor(change.path),
          type: "blob",
          sha: str(blob.data, "sha"),
        });
      }
      const newTree = await api(token, "POST", `${repoRoute}/git/trees`, {
        base_tree: baseTree,
        tree,
      });
      const commit = await api(token, "POST", `${repoRoute}/git/commits`, {
        message: `Implement issue #${input.issueNumber} (factory run ${input.runId})\n\nGenerated by an AI agent.`,
        tree: str(newTree.data, "sha"),
        parents: [input.baseSha],
      });
      // 422 means another attempt created the ref first: keep that one.
      const createdRef = await api(
        token,
        "POST",
        `${repoRoute}/git/refs`,
        { ref: `refs/heads/${branch}`, sha: str(commit.data, "sha") },
        [422],
      );
      headSha =
        createdRef.status === 422
          ? str(
              (await api(token, "GET", `${repoRoute}/git/ref/heads/${branch}`))
                .data,
              "object",
              "sha",
            )
          : str(commit.data, "sha");
    }

    const head = `${owner}:${branch}`;
    const findPr = async () => {
      const list = await api(
        token,
        "GET",
        `${repoRoute}/pulls?head=${encodeURIComponent(head)}&state=all`,
      );
      return Array.isArray(list.data) && list.data.length > 0
        ? list.data[0]
        : undefined;
    };
    let pr = await findPr();
    if (pr === undefined) {
      const created = await api(
        token,
        "POST",
        `${repoRoute}/pulls`,
        {
          title:
            `Factory: issue #${input.issueNumber} ${neutralizeMentions(input.title).slice(0, 80)}`.trim(),
          head: branch,
          base: defaultBranch,
          body: prBody(input),
        },
        [422],
      );
      pr = created.status === 422 ? await findPr() : created.data;
      if (pr === undefined) throw new Error("pull request was not created");
    }
    const prNumber = field(pr, "number");
    if (typeof prNumber !== "number")
      throw new Error("unexpected GitHub response");
    const prUrl = str(pr, "html_url");

    const comments = await api(
      token,
      "GET",
      `${repoRoute}/issues/${input.issueNumber}/comments?per_page=100`,
    );
    const already =
      Array.isArray(comments.data) &&
      comments.data.some(
        (c) =>
          typeof field(c, "body") === "string" &&
          (field(c, "body") as string).includes(prUrl),
      );
    if (!already) {
      await api(
        token,
        "POST",
        `${repoRoute}/issues/${input.issueNumber}/comments`,
        {
          body: `The factory opened ${prUrl} for this issue. The pull request is agent-generated. A second AI engine reviews it, and the risk policy of the repository decides whether it also needs an approval from an operator before it merges.`,
        },
      );
    }
    return { prNumber, prUrl, branch, headSha };
  }

  return { publish };
}
